CREATE TABLE IF NOT EXISTS ems.sys_menu (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT       DEFAULT 0 NOT NULL,
    menu_code   VARCHAR(100) NOT NULL,
    menu_name   VARCHAR(100) NOT NULL,
    menu_type   VARCHAR(20)  DEFAULT 'MENU' NOT NULL,
    path        VARCHAR(200),
    component   VARCHAR(200),
    permission  VARCHAR(100),
    icon        VARCHAR(100),
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_menu_type CHECK (menu_type IN ('DIR', 'MENU', 'BUTTON')),
    CONSTRAINT ck_sys_menu_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_menu_code ON ems.sys_menu (menu_code);
CREATE INDEX IF NOT EXISTS idx_sys_menu_tree ON ems.sys_menu (parent_id, sort_no);

COMMENT ON TABLE ems.sys_menu IS '菜单与权限';
COMMENT ON COLUMN ems.sys_menu.parent_id IS '上级菜单，0=根';
COMMENT ON COLUMN ems.sys_menu.menu_type IS 'DIR=目录，MENU=页面，BUTTON=按钮';
COMMENT ON COLUMN ems.sys_menu.component IS '前端组件相对路径';
COMMENT ON COLUMN ems.sys_menu.permission IS '权限码';
COMMENT ON COLUMN ems.sys_menu.status IS '1=启用，0=停用';
