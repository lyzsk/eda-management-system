CREATE TABLE IF NOT EXISTS ems.eda_server (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    server_code             VARCHAR(50)  NOT NULL,
    server_name             VARCHAR(100),
    host                    VARCHAR(200) NOT NULL,
    ssh_port                INTEGER      DEFAULT 22 NOT NULL,
    os_type                 VARCHAR(20)  DEFAULT 'Linux' NOT NULL,
    username                VARCHAR(100),
    host_key_fingerprint    VARCHAR(200),
    connect_timeout_seconds INTEGER      DEFAULT 10 NOT NULL,
    status                  SMALLINT     DEFAULT 1 NOT NULL,
    create_time             TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time             TIMESTAMP(6),
    remark                  VARCHAR(500),
    CONSTRAINT ck_eda_server_status CHECK (status IN (0, 1))
);

-- 方案 A：认证凭据由部署配置提供（EMS_SSH_PRIVATE_KEY / EMS_SSH_KEY_FILE），不进数据库
ALTER TABLE ems.eda_server DROP COLUMN IF EXISTS auth_type;
ALTER TABLE ems.eda_server DROP COLUMN IF EXISTS password_enc;
ALTER TABLE ems.eda_server DROP COLUMN IF EXISTS private_key_enc;
ALTER TABLE ems.eda_server DROP COLUMN IF EXISTS passphrase_enc;
ALTER TABLE ems.eda_server ALTER COLUMN username DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uk_eda_server_code ON ems.eda_server (server_code);
CREATE INDEX IF NOT EXISTS idx_eda_server_host ON ems.eda_server (host);
CREATE INDEX IF NOT EXISTS idx_eda_server_status ON ems.eda_server (status);

COMMENT ON TABLE ems.eda_server IS '服务器（SSH 执行目标；凭据由部署配置提供，不入库）';
COMMENT ON COLUMN ems.eda_server.server_code IS '服务器编码，全局唯一，如 eda-linux-01';
COMMENT ON COLUMN ems.eda_server.host IS 'IP 或域名';
COMMENT ON COLUMN ems.eda_server.ssh_port IS 'SSH 端口';
COMMENT ON COLUMN ems.eda_server.os_type IS 'Linux/Windows';
COMMENT ON COLUMN ems.eda_server.username IS 'SSH 执行账号；为空时使用全局默认账号 EMS_SSH_USER';
COMMENT ON COLUMN ems.eda_server.host_key_fingerprint IS '首次连接记录的主机指纹（预留）';
COMMENT ON COLUMN ems.eda_server.connect_timeout_seconds IS 'SSH 连接超时（秒）';
COMMENT ON COLUMN ems.eda_server.status IS '1=启用，0=停用';
