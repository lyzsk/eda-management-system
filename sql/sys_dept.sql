CREATE TABLE IF NOT EXISTS ems.sys_dept (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT       DEFAULT 0 NOT NULL,
    dept_code   VARCHAR(50)  NOT NULL,
    dept_name   VARCHAR(100) NOT NULL,
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_dept_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_dept_code ON ems.sys_dept (dept_code);
CREATE INDEX IF NOT EXISTS idx_sys_dept_tree ON ems.sys_dept (parent_id, sort_no);

COMMENT ON TABLE ems.sys_dept IS '部门';
COMMENT ON COLUMN ems.sys_dept.parent_id IS '上级部门；公司根节点 id=0，数据中心 parent_id=0';
COMMENT ON COLUMN ems.sys_dept.status IS '1=启用，0=停用';
