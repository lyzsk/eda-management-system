CREATE TABLE IF NOT EXISTS ems.sys_dict_data (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dict_type   VARCHAR(100) NOT NULL,
    label       VARCHAR(100) NOT NULL,
    dict_value  VARCHAR(100) NOT NULL,
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_dict_data_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_dict_data ON ems.sys_dict_data (dict_type, dict_value);
CREATE INDEX IF NOT EXISTS idx_sys_dict_data_type ON ems.sys_dict_data (dict_type, sort_no);

COMMENT ON TABLE ems.sys_dict_data IS '字典数据';
COMMENT ON COLUMN ems.sys_dict_data.dict_type IS '字典类型编码';
COMMENT ON COLUMN ems.sys_dict_data.label IS '显示文本';
COMMENT ON COLUMN ems.sys_dict_data.dict_value IS '存储值';
COMMENT ON COLUMN ems.sys_dict_data.status IS '1=启用，0=停用';
