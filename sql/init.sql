-- EDA Management System · idempotent init
BEGIN;
CREATE SCHEMA IF NOT EXISTS ems;
CREATE TABLE IF NOT EXISTS ems.sys_user (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)  NOT NULL,
    password    VARCHAR(100) NOT NULL,
    real_name   VARCHAR(50)  NOT NULL,
    gender      SMALLINT     DEFAULT 0 NOT NULL,
    email       VARCHAR(100),
    mobile      VARCHAR(20),
    avatar      VARCHAR(500),
    dept_id     BIGINT,
    role_code   VARCHAR(50)  DEFAULT 'USER' NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_user_gender CHECK (gender IN (0, 1, 2)),
    CONSTRAINT ck_sys_user_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_user_username ON ems.sys_user (username);
CREATE INDEX IF NOT EXISTS idx_sys_user_dept ON ems.sys_user (dept_id);
CREATE INDEX IF NOT EXISTS idx_sys_user_status ON ems.sys_user (status);

COMMENT ON TABLE ems.sys_user IS '系统用户';
COMMENT ON COLUMN ems.sys_user.username IS '登录账号，全局唯一';
COMMENT ON COLUMN ems.sys_user.password IS 'BCrypt 密码';
COMMENT ON COLUMN ems.sys_user.real_name IS '真实姓名';
COMMENT ON COLUMN ems.sys_user.gender IS '0=未知，1=男，2=女';
COMMENT ON COLUMN ems.sys_user.dept_id IS '部门 ID';
COMMENT ON COLUMN ems.sys_user.role_code IS '角色编码';
COMMENT ON COLUMN ems.sys_user.status IS '1=启用，0=停用';
CREATE TABLE IF NOT EXISTS ems.sys_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code   VARCHAR(50)  NOT NULL,
    role_name   VARCHAR(100) NOT NULL,
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_role_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_role_code ON ems.sys_role (role_code);

COMMENT ON TABLE ems.sys_role IS '系统角色';
COMMENT ON COLUMN ems.sys_role.role_code IS '角色编码，全局唯一';
COMMENT ON COLUMN ems.sys_role.role_name IS '角色名称';
COMMENT ON COLUMN ems.sys_role.status IS '1=启用，0=停用';
CREATE TABLE IF NOT EXISTS ems.sys_menu (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT       DEFAULT 0 NOT NULL,
    menu_code   VARCHAR(100) NOT NULL,
    menu_name   VARCHAR(100) NOT NULL,
    menu_type   VARCHAR(20)  DEFAULT 'MENU' NOT NULL,
    path        VARCHAR(200),
    component   VARCHAR(200),
    permission  VARCHAR(100),
    icon        VARCHAR(100),
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_menu_type CHECK (menu_type IN ('DIR', 'MENU', 'BUTTON')),
    CONSTRAINT ck_sys_menu_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_menu_code ON ems.sys_menu (menu_code);
CREATE INDEX IF NOT EXISTS idx_sys_menu_tree ON ems.sys_menu (parent_id, sort_no);

COMMENT ON TABLE ems.sys_menu IS '菜单与权限';
COMMENT ON COLUMN ems.sys_menu.parent_id IS '上级菜单，0=根';
COMMENT ON COLUMN ems.sys_menu.menu_type IS 'DIR=目录，MENU=页面，BUTTON=按钮';
COMMENT ON COLUMN ems.sys_menu.component IS '前端组件相对路径';
COMMENT ON COLUMN ems.sys_menu.permission IS '权限码';
COMMENT ON COLUMN ems.sys_menu.status IS '1=启用，0=停用';
CREATE TABLE IF NOT EXISTS ems.sys_dept (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id   BIGINT       DEFAULT 0 NOT NULL,
    dept_code   VARCHAR(50)  NOT NULL,
    dept_name   VARCHAR(100) NOT NULL,
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_dept_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_dept_code ON ems.sys_dept (dept_code);
CREATE INDEX IF NOT EXISTS idx_sys_dept_tree ON ems.sys_dept (parent_id, sort_no);

COMMENT ON TABLE ems.sys_dept IS '部门';
COMMENT ON COLUMN ems.sys_dept.parent_id IS '上级部门；公司根节点 id=0，数据中心 parent_id=0';
COMMENT ON COLUMN ems.sys_dept.status IS '1=启用，0=停用';
CREATE TABLE IF NOT EXISTS ems.sys_dict_type (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dict_type   VARCHAR(100) NOT NULL,
    dict_name   VARCHAR(100) NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_dict_type_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_dict_type ON ems.sys_dict_type (dict_type);

COMMENT ON TABLE ems.sys_dict_type IS '字典类型';
COMMENT ON COLUMN ems.sys_dict_type.dict_type IS '字典类型编码，全局唯一';
COMMENT ON COLUMN ems.sys_dict_type.status IS '1=启用，0=停用';
CREATE TABLE IF NOT EXISTS ems.sys_dict_data (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dict_type   VARCHAR(100) NOT NULL,
    label       VARCHAR(100) NOT NULL,
    dict_value  VARCHAR(100) NOT NULL,
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_dict_data_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_dict_data ON ems.sys_dict_data (dict_type, dict_value);
CREATE INDEX IF NOT EXISTS idx_sys_dict_data_type ON ems.sys_dict_data (dict_type, sort_no);

COMMENT ON TABLE ems.sys_dict_data IS '字典数据';
COMMENT ON COLUMN ems.sys_dict_data.dict_type IS '字典类型编码';
COMMENT ON COLUMN ems.sys_dict_data.label IS '显示文本';
COMMENT ON COLUMN ems.sys_dict_data.dict_value IS '存储值';
COMMENT ON COLUMN ems.sys_dict_data.status IS '1=启用，0=停用';
CREATE TABLE IF NOT EXISTS ems.eda_tool (
