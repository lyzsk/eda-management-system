    update_time    TIMESTAMP(6),
    remark         VARCHAR(500),
    CONSTRAINT ck_eda_tool_status CHECK (status IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_eda_tool_host ON ems.eda_tool (host);
CREATE INDEX IF NOT EXISTS idx_eda_tool_status ON ems.eda_tool (status);

