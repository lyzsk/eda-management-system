ALTER TABLE ems.eda_server DROP COLUMN IF EXISTS passphrase_enc;
ALTER TABLE ems.eda_server ALTER COLUMN username DROP NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uk_eda_server_code ON ems.eda_server (server_code);
CREATE INDEX IF NOT EXISTS idx_eda_server_host ON ems.eda_server (host);
CREATE INDEX IF NOT EXISTS idx_eda_server_status ON ems.eda_server (status);

COMMENT ON TABLE ems.eda_server IS '服务器（SSH 执行目标；凭据由部署配置提供，不入库）';
COMMENT ON COLUMN ems.eda_server.server_code IS '服务器编码，全局唯一，如 eda-linux-01';
COMMENT ON COLUMN ems.eda_server.username IS 'SSH 执行账号；为空时使用全局默认账号 EMS_SSH_USER';
COMMENT ON COLUMN ems.eda_server.status IS '1=启用，0=停用';

CREATE TABLE IF NOT EXISTS ems.eda_script (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_id         BIGINT       NOT NULL,
    action          VARCHAR(20)  NOT NULL,
    script_name     VARCHAR(100) NOT NULL,
    exec_mode       VARCHAR(20)  DEFAULT 'SHELL' NOT NULL,
    command         TEXT         NOT NULL,
    workdir         VARCHAR(500),
    timeout_seconds INTEGER      DEFAULT 60 NOT NULL,
    enabled         SMALLINT     DEFAULT 1 NOT NULL,
    sort_no         INTEGER      DEFAULT 0 NOT NULL,
    create_time     TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time     TIMESTAMP(6),
    remark          VARCHAR(500),
    CONSTRAINT ck_eda_script_action CHECK (action IN ('START', 'STOP', 'RESTART', 'STATUS', 'TASK')),
    CONSTRAINT ck_eda_script_exec_mode CHECK (exec_mode IN ('SHELL', 'SCRIPT', 'POWERSHELL')),
    CONSTRAINT ck_eda_script_enabled CHECK (enabled IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_eda_script_tool ON ems.eda_script (tool_id, sort_no);
CREATE INDEX IF NOT EXISTS idx_eda_script_action ON ems.eda_script (action);

COMMENT ON TABLE ems.eda_script IS 'EDA 服务操作脚本（启动/停止/重启/状态/任务）';
COMMENT ON COLUMN ems.eda_script.tool_id IS '关联 eda_tool.id';
COMMENT ON COLUMN ems.eda_script.command IS '登记好的完整命令；只允许管理员维护';

CREATE TABLE IF NOT EXISTS ems.eda_script_run (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id        VARCHAR(40)  NOT NULL,
    script_id     BIGINT       NOT NULL,
    tool_id       BIGINT       NOT NULL,
    server_id     BIGINT       NOT NULL,
    action        VARCHAR(20)  NOT NULL,
    operator_name VARCHAR(100),
    status        VARCHAR(20)  DEFAULT 'PENDING' NOT NULL,
    exit_code     INTEGER,
    output        TEXT,
    error_msg     VARCHAR(2000),
    ssh_host      VARCHAR(200),
    started_at    TIMESTAMP(6),
    finished_at   TIMESTAMP(6),
    create_time   TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time   TIMESTAMP(6),
    remark        VARCHAR(500),
    CONSTRAINT ck_eda_script_run_status CHECK (status IN ('PENDING', 'RUNNING', 'SUCCESS', 'FAILED', 'TIMEOUT'))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_eda_script_run_id ON ems.eda_script_run (run_id);
CREATE INDEX IF NOT EXISTS idx_eda_script_run_script ON ems.eda_script_run (script_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_eda_script_run_tool ON ems.eda_script_run (tool_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_eda_script_run_status ON ems.eda_script_run (status);

COMMENT ON TABLE ems.eda_script_run IS '脚本执行历史';
COMMENT ON COLUMN ems.eda_script_run.run_id IS '执行批次号（UUID），前端轮询用';
COMMENT ON COLUMN ems.eda_script_run.status IS 'PENDING/RUNNING/SUCCESS/FAILED/TIMEOUT';
