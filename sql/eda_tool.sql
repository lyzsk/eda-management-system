CREATE TABLE IF NOT EXISTS ems.eda_tool (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tool_name      VARCHAR(100) NOT NULL,
    tool_type      VARCHAR(50),
    host           VARCHAR(200),
    os_type        VARCHAR(20),
    tool_version   VARCHAR(100),
    license_status VARCHAR(30),
    status         SMALLINT     DEFAULT 1 NOT NULL,
    last_heartbeat TIMESTAMP(6),
    create_time    TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time    TIMESTAMP(6),
    remark         VARCHAR(500),
    CONSTRAINT ck_eda_tool_status CHECK (status IN (0, 1))
);

CREATE INDEX IF NOT EXISTS idx_eda_tool_host ON ems.eda_tool (host);
CREATE INDEX IF NOT EXISTS idx_eda_tool_status ON ems.eda_tool (status);

COMMENT ON TABLE ems.eda_tool IS 'EDA 工具清单';
COMMENT ON COLUMN ems.eda_tool.tool_name IS '工具名称';
COMMENT ON COLUMN ems.eda_tool.tool_type IS '工具类型';
COMMENT ON COLUMN ems.eda_tool.host IS '部署主机';
COMMENT ON COLUMN ems.eda_tool.os_type IS 'Linux/Windows';
COMMENT ON COLUMN ems.eda_tool.tool_version IS '版本';
COMMENT ON COLUMN ems.eda_tool.license_status IS 'License 状态';
COMMENT ON COLUMN ems.eda_tool.status IS '1=在线，0=离线';
COMMENT ON COLUMN ems.eda_tool.last_heartbeat IS '最后心跳时间';
