CREATE TABLE IF NOT EXISTS ems.sys_role (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_code   VARCHAR(50)  NOT NULL,
    role_name   VARCHAR(100) NOT NULL,
    sort_no     INTEGER      DEFAULT 0 NOT NULL,
    status      SMALLINT     DEFAULT 1 NOT NULL,
    create_time TIMESTAMP(6) DEFAULT now() NOT NULL,
    update_time TIMESTAMP(6),
    remark      VARCHAR(500),
    CONSTRAINT ck_sys_role_status CHECK (status IN (0, 1))
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_sys_role_code ON ems.sys_role (role_code);

COMMENT ON TABLE ems.sys_role IS '系统角色';
COMMENT ON COLUMN ems.sys_role.role_code IS '角色编码，全局唯一';
COMMENT ON COLUMN ems.sys_role.role_name IS '角色名称';
COMMENT ON COLUMN ems.sys_role.status IS '1=启用，0=停用';
